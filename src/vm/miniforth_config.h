#ifndef MINIFORTH_CONFIG_H
#define MINIFORTH_CONFIG_H

// Build target configuration
#ifndef MINIFORTH_TARGET
#define MINIFORTH_TARGET_HOSTED 1
#define MINIFORTH_TARGET_ARM_BAREMETAL 0
#else
#if MINIFORTH_TARGET == ARM_BAREMETAL
#define MINIFORTH_TARGET_HOSTED 0
#define MINIFORTH_TARGET_ARM_BAREMETAL 1
#else
#define MINIFORTH_TARGET_HOSTED 1
#define MINIFORTH_TARGET_ARM_BAREMETAL 0
#endif
#endif

// Size optimization levels
#ifndef MINIFORTH_SIZE_OPTIMIZE
#define MINIFORTH_SIZE_OPTIMIZE 0  // 0=none, 1=moderate, 2=aggressive
#endif

// Core VM configuration
#define MINIFORTH_WORD_SIZE 16

// Memory sizes for different targets
#if MINIFORTH_TARGET_ARM_BAREMETAL
// Microcontroller: smaller memory footprint
#define MINIFORTH_DEFAULT_CODE_SIZE 128
#define MINIFORTH_DEFAULT_DATA_SIZE 64
#define MINIFORTH_DEFAULT_STACK_SIZE 16
#else
// Hosted: more generous memory
#define MINIFORTH_DEFAULT_CODE_SIZE 512
#define MINIFORTH_DEFAULT_DATA_SIZE 256
#define MINIFORTH_DEFAULT_STACK_SIZE 32
#endif

// Feature flags based on size optimization level
#if MINIFORTH_SIZE_OPTIMIZE >= 2
// Aggressive size optimization: minimal features
#define MINIFORTH_ENABLE_DEBUGGING 0
#define MINIFORTH_ENABLE_BOUNDS_CHECK 0
#define MINIFORTH_ENABLE_ERROR_STRINGS 0
#define MINIFORTH_ENABLE_FLOAT 0
#define MINIFORTH_ENABLE_BYTE_ACCESS 0
#define MINIFORTH_ENABLE_UTILITY_FUNCTIONS 0
#elif MINIFORTH_SIZE_OPTIMIZE >= 1
// Moderate size optimization: essential debugging only
#define MINIFORTH_ENABLE_DEBUGGING 0
#define MINIFORTH_ENABLE_BOUNDS_CHECK 1
#define MINIFORTH_ENABLE_ERROR_STRINGS 0
#define MINIFORTH_ENABLE_FLOAT 0
#define MINIFORTH_ENABLE_BYTE_ACCESS 1
#define MINIFORTH_ENABLE_UTILITY_FUNCTIONS 1
#else
// No size optimization: all features
#define MINIFORTH_ENABLE_DEBUGGING 1
#define MINIFORTH_ENABLE_BOUNDS_CHECK 1
#define MINIFORTH_ENABLE_ERROR_STRINGS 1
#define MINIFORTH_ENABLE_FLOAT 0
#define MINIFORTH_ENABLE_BYTE_ACCESS 1
#define MINIFORTH_ENABLE_UTILITY_FUNCTIONS 1
#endif

// ARM bare-metal specific overrides
#if MINIFORTH_TARGET_ARM_BAREMETAL
#undef MINIFORTH_ENABLE_DEBUGGING
#define MINIFORTH_ENABLE_DEBUGGING 0
#undef MINIFORTH_ENABLE_ERROR_STRINGS
#define MINIFORTH_ENABLE_ERROR_STRINGS 0
#undef MINIFORTH_ENABLE_FLOAT
#define MINIFORTH_ENABLE_FLOAT 0
#endif

// Instruction set configuration
#define MINIFORTH_ENABLE_EXTENDED_OPCODES 1

// Memory allocation strategy
#if MINIFORTH_TARGET_ARM_BAREMETAL
#define MINIFORTH_USE_STATIC_ALLOCATION 1
#define MINIFORTH_USE_MALLOC 0
#else
#define MINIFORTH_USE_STATIC_ALLOCATION 0
#define MINIFORTH_USE_MALLOC 1
#endif

#endif // MINIFORTH_CONFIG_H